function asAnswer({ id, title, text, view, target = null }) {
  return { id, title, text, view, target };
}

export function faqFor(role) {
  return entries.filter((entry) => entry.roles.includes(role)).map((entry) => ({
    ...asAnswer(entry), terms: entry.terms.map((term) => term.replaceAll('*', '')),
  }));
}

function tokenize(value, allowWildcard = false) {
  const normalized = value.normalize('NFKC').toLowerCase().replaceAll('ё', 'е');
  return normalized.match(allowWildcard ? /[\p{L}\p{N}]+\*?/gu : /[\p{L}\p{N}]+/gu) ?? [];
}

const keywords = new Map(entries.map((entry) => [entry.id, entry.terms.map((term) => tokenize(term, true))]));

function matchScore(entry, words) {
  let score = 0;
  for (const alias of keywords.get(entry.id)) {
    const matches = alias.every((token) => (token.endsWith('*')
      ? words.some((word) => word.startsWith(token.slice(0, -1)))
      : words.includes(token)));
    if (matches) score = Math.max(score, alias.length * 100 + alias.join('').length);
  }
  return score;
}

export function answerFor(role, query) {
  const words = typeof query === 'string' ? tokenize(query) : [];
  const removes = words.some((word) => /^(удал|стер|очист)/.test(word));
  const withdraws = words.some((word) => /^(отозва|отзыва|отзыв|отменить|отмена$)/.test(word));
  let best;
  let bestScore = 0;
  for (const entry of entries) {
    if (!entry.roles.includes(role)) continue;
    if (removes || (withdraws && entry.id !== 'withdraw-appeal')) continue;
    const score = matchScore(entry, words);
    if (score && entry.id === 'document-requirements') return { answer: asAnswer(entry), found: true };
    if (score <= bestScore) continue;
    best = entry;
    bestScore = score;
  }
  if (best) return { answer: asAnswer(best), found: true };
  const contact = role === 'student'
    ? 'Откройте «Сообщения» и напишите в диалоге «Деканат».'
    : 'За уточнением можно обратиться в деканат. Доступные диалоги находятся в разделе «Сообщения».';
  return {
    answer: { id: 'unknown', title: 'Ответа пока нет', text: `В базе помощника пока нет ответа на этот вопрос. ${contact}`,
      view: 'messages', target: null },
    found: false,
  };
}
